ZW = "​"


def zw(s):
    return ZW.join(str(s))


def zw_article(a):
    a = copy.deepcopy(a)
    for k in ("title", "description", "conclusion", "lead", "next_step"):
        a[k] = zw(a[k])
    a["can_do"] = [zw(x) for x in a["can_do"]]
    a["checklist"] = [zw(x) for x in a["checklist"]]
    for s in a["sections"]:
        s["heading"] = zw(s["heading"])
        for b in s["blocks"]:
            if "text" in b:
                b["text"] = zw(b["text"])
            for key in ("items", "lines"):
                if key in b:
                    b[key] = [zw(x) for x in b[key]]
            if "rows" in b:
                b["rows"] = [[zw(c) for c in r] for r in b["rows"]]
    for f in a["faq"]:
        f["q"], f["a"] = zw(f["q"]), zw(f["a"])
    return a


